// Maps an Open-Meteo/WMO weather_code to the matching icon bitmap.
static inline const uint8_t* weatherCodeToIcon(int code) {
  if (code == 0) return weather_icon_sun;
  if (code >= 1 && code <= 3) return weather_icon_cloud;
  if (code == 45 || code == 48) return weather_icon_fog;
  if (code >= 51 && code <= 67) return weather_icon_rain;
  if (code >= 71 && code <= 77) return weather_icon_snow;
  if (code >= 80 && code <= 82) return weather_icon_rain;
  if (code >= 85 && code <= 86) return weather_icon_snow;
  if (code >= 95 && code <= 99) return weather_icon_storm;
  return weather_icon_cloud;
}
