// deg is the meteorological "wind from" bearing (0=N, 90=E, ...); arrow
// points in that same compass direction, like a wind vane.
static inline const uint8_t* windDegToArrow(int deg) {
  static const uint8_t* arrows[8] = {
    wind_arrow_N, wind_arrow_NE, wind_arrow_E, wind_arrow_SE,
    wind_arrow_S, wind_arrow_SW, wind_arrow_W, wind_arrow_NW
  };
  if (deg < 0) return wind_arrow_N;
  int idx = ((deg + 22) / 45) % 8;
  return arrows[idx];
}

static inline const char* windDegToCompass(int deg) {
  static const char* labels[8] = { "N", "NE", "E", "SE", "S", "SW", "W", "NW" };
  if (deg < 0) return "";
  int idx = ((deg + 22) / 45) % 8;
  return labels[idx];
}
